/** Шешім мәтінінің бірінші түсіндірме сөйлемі және бірінші математикалық қадамы (2-саты). */
function firstStep(solution: string): string | null {
  const text = solution.replace(/\r/g, '');
  const firstPara = text.split('\n').map((s) => s.trim()).find((s) => s && !s.startsWith('$$') && !/^Жауабы/.test(s) && !/^\*\*?1-тәсіл/.test(s));
  const steps = solutionSteps(text);
  const parts: string[] = [];
  if (firstPara && firstPara.length < 400) parts.push(firstPara);
  if (steps.length > 1) parts.push(`Бірінші қадам: $${steps[0]}$`);
  return parts.length ? parts.join('\n') : null;
}

export function buildHint(level: number, ctx: { objectiveCodes: string[]; solutionText: string }): string {
  if (level <= 1) {
    for (const c of ctx.objectiveCodes) if (OBJ_HINT[c]) return OBJ_HINT[c];
    const fs = firstStep(ctx.solutionText);
    return fs ? fs.split('\n')[0] : 'Шартты қайта оқып, берілгенді және ізделгенді жазып алыңыз. Қандай формула осы шамаларды байланыстырады?';
  }
  return firstStep(ctx.solutionText) ?? 'Шешімнің бірінші қадамы бұл есепте бөлек жазылмаған — «Тексеру және шешімін көру» батырмасын қолданыңыз.';
}

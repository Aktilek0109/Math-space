export const HINT_PENALTY = 0.25;
export const MAX_HINT_LEVEL = 2;

/** Кеңес саны бойынша балды азайту коэффициенті */
export function hintFactor(hintsUsed: number | null | undefined): number {
  const h = Math.max(0, Math.min(MAX_HINT_LEVEL, Number(hintsUsed ?? 0)));
  return Math.max(0, 1 - HINT_PENALTY * h);
}


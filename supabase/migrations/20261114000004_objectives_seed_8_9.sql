from public.questions q
join public.learning_objectives lo on lo.unit_id = q.unit_id and lo.code in ('9.2.2.3', '9.2.2.4')
where not exists (select 1 from public.question_topics qt where qt.question_id = q.id)
on conflict do nothing;

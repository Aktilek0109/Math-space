insert into public.topic_objectives (topic_id, objective_id)
select t.id, lo.id
from m
join public.units u on u.grade = m.grade
join public.topics t on t.unit_id = u.id and t.title like m.topic_prefix || '%'
join public.learning_objectives lo on lo.grade = m.grade and lo.code = m.code
on conflict do nothing;

-- Банктегі есеп → мақсат: тақырыбының мақсаттары тең салмақпен
insert into public.question_objectives (question_id, objective_id, weight)
select qt.question_id, tob.objective_id,
       round(1.0 / count(*) over (partition by qt.question_id), 4)
from (select distinct on (question_id) question_id, topic_id from public.question_topics order by question_id, topic_id) qt
join public.topic_objectives tob on tob.topic_id = qt.topic_id
on conflict do nothing;

